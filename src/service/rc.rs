//! rc.d on FreeBSD: the core as a root rc.d service supervised by daemon(8), and the scheduled
//! refresh as a user crontab entry (`@<seconds>`, which FreeBSD cron runs without overlap).

use super::{GEODATA, check_installable, sudo_sh};
use crate::settings::{self, Paths, Settings};
use anyhow::{Context, Result, bail};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

pub const MANAGER: &str = "rc.d";
pub const CORE_NAME: &str = "mihoctl_core";
pub const REFRESH_NAME: &str = "mihoctl_refresh";

/// Root-owned copy of mihomo, following the ports prefix.
const BIN_DIR: &str = "/usr/local/libexec/mihoctl";
/// Root-owned state: the core's `-d` home `core/`.
const ROOT_DIR: &str = "/var/db/mihoctl";
/// Root-only logs, like the other backends.
const CORE_LOG_DIR: &str = "/var/log/mihoctl";

const BEGIN: &str = "# mihoctl_refresh begin";
const END: &str = "# mihoctl_refresh end";

fn rc_script_path() -> PathBuf {
    PathBuf::from(format!("/usr/local/etc/rc.d/{CORE_NAME}"))
}

fn core_bin() -> PathBuf {
    Path::new(BIN_DIR).join("mihomo")
}

fn core_home() -> PathBuf {
    Path::new(ROOT_DIR).join("core")
}

pub fn installed_mihomo() -> Option<PathBuf> {
    Some(core_bin())
}

/// One shell word, with no expansion at all.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Cron turns an unescaped `%` into a newline before the shell sees the command.
fn cron_quote(s: &str) -> String {
    sh_quote(s).replace('%', r"\%")
}

/// The core child is root-owned, so an unprivileged `status` can't read the 0600 pidfile;
/// pgrep sees every process's argv instead. ERE-escape the root-owned binary path, which is also
/// the child's argv[0] (the `daemon[pid]` supervisor does not match).
fn regex_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if "\\.^$|?*+()[]{}".contains(c) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

fn core_pattern() -> String {
    format!(r"^{}( |$)", regex_escape(&core_bin().to_string_lossy()))
}

/// `daemon(8)` supervises (`-r` restarts on exit) and keeps `-P` holding the supervisor PID, which
/// is what `stop` must signal. `-f` detaches its stdio: without it the supervisor inherits the
/// caller's pipes and `service start` over SSH never returns. The pidfile is 0600, so unprivileged
/// `status` falls back to pgrep.
fn core_script(paths: &Paths) -> String {
    let q = |p: &Path| sh_quote(&p.to_string_lossy());
    format!(
        r#"#!/bin/sh
#
# PROVIDE: mihoctl_core
# REQUIRE: NETWORKING
# KEYWORD: shutdown
#
# Generated by `mihoctl service install`; edits are overwritten.

. /etc/rc.subr

name="mihoctl_core"
rcvar="mihoctl_core_enable"
desc="mihomo core (managed by mihoctl)"

load_rc_config "$name"
: ${{mihoctl_core_enable:=NO}}

pidfile="/var/run/mihoctl_core.pid"
mihoctl_core_bin={bin}
mihoctl_core_home={home}
mihoctl_core_config={config}
mihoctl_core_log={log}
mihoctl_core_pattern={pattern}

start_cmd="mihoctl_core_start"
stop_cmd="mihoctl_core_stop"
status_cmd="mihoctl_core_status"

mihoctl_core_running()
{{
    if [ -r "$pidfile" ] && /usr/bin/pgrep -q -F "$pidfile" -L daemon; then
        return 0
    fi
    /usr/bin/pgrep -q -f "$mihoctl_core_pattern"
}}

mihoctl_core_start()
{{
    if mihoctl_core_running; then
        echo "${{name}} already running." >&2
        return 1
    fi
    if [ ! -f "$mihoctl_core_config" ]; then
        echo "${{name}}: $mihoctl_core_config is missing; run 'mihoctl apply' first." >&2
        return 1
    fi
    umask 077
    /usr/sbin/daemon -f -r -P "$pidfile" -o "$mihoctl_core_log" \
        "$mihoctl_core_bin" -d "$mihoctl_core_home" -f "$mihoctl_core_config"
}}

mihoctl_core_stop()
{{
    if ! mihoctl_core_running; then
        echo "${{name}} not running."
        return 1
    fi
    if [ ! -r "$pidfile" ]; then
        echo "${{name}}: cannot read $pidfile to signal the supervisor" >&2
        return 1
    fi
    if /usr/bin/pgrep -q -F "$pidfile" -L daemon; then
        _pid=$(cat "$pidfile")
    else
        # A stale pidfile with an orphaned child (the supervisor was killed): stop the child.
        _pid=$(/usr/bin/pgrep -f "$mihoctl_core_pattern" | head -n 1)
    fi
    if [ -z "$_pid" ]; then
        echo "${{name}}: no process to stop" >&2
        return 1
    fi
    echo "Stopping ${{name}}."
    kill -TERM "$_pid"
    wait_for_pids "$_pid"
}}

mihoctl_core_status()
{{
    if mihoctl_core_running; then
        echo "${{name}} is running."
        return 0
    fi
    echo "${{name}} is not running."
    return 1
}}

run_rc_command "$1"
"#,
        bin = q(&core_bin()),
        home = q(&core_home()),
        config = q(&paths.config()),
        log = q(&Path::new(CORE_LOG_DIR).join("core.log")),
        pattern = sh_quote(&core_pattern()),
    )
}

fn refresh_block(exe: &Path, settings_file: &Path, log: &Path, secs: u64, path: &str) -> String {
    format!(
        "{BEGIN}\n@{secs} umask 077; MIHOCTL_CONFIG={} PATH={} {} refresh >> {} 2>&1\n{END}\n",
        cron_quote(&settings_file.to_string_lossy()),
        cron_quote(path),
        cron_quote(&exe.to_string_lossy()),
        cron_quote(&log.to_string_lossy())
    )
}

fn refresh_entry(settings: &Settings, paths: &Paths) -> Result<String> {
    let exe = std::env::current_exe()?.canonicalize()?;
    let cfg = paths.settings_file.canonicalize()?;
    // FreeBSD cron's @N schedules N seconds after the previous run completes, without overlap.
    let secs = settings::parse_duration(&settings.refresh_interval)?.as_secs().max(1);
    let path = std::env::var("PATH").unwrap_or_else(|_| "/usr/local/bin:/usr/bin:/bin".into());
    Ok(refresh_block(&exe, &cfg, &paths.core_dir.join("refresh.log"), secs, &path))
}

fn strip_block(current: &str) -> String {
    let mut out = String::new();
    let mut skipping = false;
    for line in current.lines() {
        if line.trim() == BEGIN {
            skipping = true;
        } else if skipping {
            if line.trim() == END {
                skipping = false;
            }
        } else {
            out.push_str(line);
            out.push('\n');
        }
    }
    out
}

/// Replace our managed crontab block, leaving every other entry untouched.
fn replace_block(current: &str, block: &str) -> String {
    let kept = strip_block(current);
    let kept = kept.trim_end();
    let block = block.trim_end();
    let mut out = String::new();
    if !kept.is_empty() {
        out.push_str(kept);
        out.push_str(if block.is_empty() { "\n" } else { "\n\n" });
    }
    if !block.is_empty() {
        out.push_str(block);
        out.push('\n');
    }
    out
}

fn scheduled(current: &str) -> bool {
    let mut inside = false;
    for line in current.lines() {
        let line = line.trim();
        if line == BEGIN {
            inside = true;
        } else if line == END {
            inside = false;
        } else if inside && line.starts_with('@') {
            return true;
        }
    }
    false
}

fn crontab() -> Result<String> {
    let out = Command::new("/usr/bin/crontab").arg("-l").output().context("running crontab -l")?;
    if out.status.success() {
        return String::from_utf8(out.stdout).context("crontab -l output");
    }
    let err = String::from_utf8_lossy(&out.stderr);
    // `crontab -l` fails when the user has no crontab yet; that is the normal first install.
    if err.contains("no crontab") {
        Ok(String::new())
    } else {
        bail!("crontab -l failed ({}): {}", out.status, err.trim())
    }
}

fn set_crontab(text: &str) -> Result<()> {
    let mut child = Command::new("/usr/bin/crontab").arg("-").stdin(Stdio::piped()).spawn().context("running crontab")?;
    // Wait even if the write fails: an early crontab exit breaks the pipe, and its status is the
    // error worth reporting.
    let written = child.stdin.take().context("crontab stdin")?.write_all(text.as_bytes());
    let status = child.wait().context("running crontab")?;
    if !status.success() {
        bail!("installing the crontab entry failed ({status})");
    }
    written.context("writing to crontab")
}

/// `(install path, contents)` of every unit, for `service print`.
pub fn units(settings: &Settings, paths: &Paths) -> Result<Vec<(PathBuf, String)>> {
    Ok(vec![(rc_script_path(), core_script(paths)), (PathBuf::from("user crontab"), refresh_entry(settings, paths)?)])
}

pub fn core_loaded() -> bool {
    Command::new("/usr/bin/pgrep")
        .args(["-q", "-f", &core_pattern()])
        .status()
        .is_ok_and(|s| s.success())
}

pub fn refresh_loaded() -> bool {
    crontab().is_ok_and(|text| scheduled(&text))
}

/// Root steps of `install`: `$1` name, `$2` ROOT_DIR, `$3` BIN_DIR, `$4` log dir, `$5` user
/// mihomo, `$6` rc.d script, `$7` user core_dir, `$8…` geodata names; the script arrives on stdin.
/// Ownership and modes are reset recursively (`-R` never follows symlinks) in case the tree
/// predates this layout. Geodata is copied 0600 so a symlink planted in `core_dir` can't expose a
/// root-only file. Logs are created 0600 rather than trusting daemon(8)'s defaults.
const INSTALL_SH: &str = r#"name=$1 root=$2 bin=$3 logs=$4 src=$5 script=$6 seed=$7; shift 7
umask 077
install -d -o root -g wheel -m 755 "$root" "$root/core" "$bin" "$logs" /usr/local/etc/rc.d /etc/rc.conf.d
chown -R root:wheel "$root" "$bin" "$logs"
chmod -R go-w "$root" "$bin" "$logs"
[ -e "$logs/core.log" ] || : > "$logs/core.log"
chmod 600 "$logs/core.log"
install -o root -g wheel -m 755 "$src" "$bin/mihomo"
for f in "$@"; do
  if [ -f "$seed/$f" ] && [ ! -e "$root/core/$f" ]; then install -o root -g wheel -m 600 "$seed/$f" "$root/core/$f"; fi
done
cat > "$script.tmp"
chmod 755 "$script.tmp"
mv -f "$script.tmp" "$script"
printf '%s_enable="YES"\n' "$name" > /etc/rc.conf.d/mihoctl_core
chmod 644 /etc/rc.conf.d/mihoctl_core
/usr/sbin/service "$name" restart"#;

/// Copies `settings.mihomo` into the root-owned tree, so rerun this after upgrading mihomo.
pub fn install(settings: &Settings, paths: &Paths) -> Result<()> {
    check_installable(settings, paths)?;
    let entry = refresh_entry(settings, paths)?;

    let script = core_script(paths);
    let script_path = rc_script_path().to_string_lossy().into_owned();
    let seed = paths.core_dir.to_string_lossy().into_owned();
    let mut args = vec![CORE_NAME, ROOT_DIR, BIN_DIR, CORE_LOG_DIR, settings.mihomo.as_str(), &script_path, &seed];
    args.extend(GEODATA);
    sudo_sh(INSTALL_SH, &args, &script)?;

    set_crontab(&replace_block(&crontab()?, &entry))
}

/// `$1` name, `$2` rc.d script, `$3` ROOT_DIR, `$4` BIN_DIR. Logs are kept, as on the other
/// backends. `onestop` ignores `*_enable="NO"` in case the user disabled a still-running service.
const UNINSTALL_SH: &str = r#"/usr/sbin/service "$1" onestop >/dev/null 2>&1 || true
rm -f "$2" "/etc/rc.conf.d/$1" /var/run/mihoctl_core.pid
rm -rf "$3" "$4""#;

pub fn uninstall() -> Result<()> {
    let current = crontab()?;
    if current.lines().any(|line| line.trim() == BEGIN) {
        let next = replace_block(&current, "");
        if next.trim().is_empty() {
            let _ = Command::new("/usr/bin/crontab").args(["-r", "-f"]).status();
        } else {
            set_crontab(&next)?;
        }
    }
    sudo_sh(UNINSTALL_SH, &[CORE_NAME, &rc_script_path().to_string_lossy(), ROOT_DIR, BIN_DIR], "")
}

/// Restart the core process (needed after changing `tun:`; plain reloads keep the TUN).
pub fn restart_core() -> Result<()> {
    sudo_sh(r#"/usr/sbin/service "$1" restart"#, &[CORE_NAME], "")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn paths() -> Paths {
        Paths::new("/home/u/m.toml".into(), "/home/u/.config".into(), "/home/u/core".into())
    }

    #[test]
    fn core_script_runs_only_root_owned_paths() {
        let script = core_script(&paths());
        assert!(script.contains("mihoctl_core_bin='/usr/local/libexec/mihoctl/mihomo'"));
        assert!(script.contains("mihoctl_core_home='/var/db/mihoctl/core'"));
        assert!(script.contains("mihoctl_core_config='/home/u/core/config.yaml'"));
        assert!(script.contains(r#"/usr/sbin/daemon -f -r -P "$pidfile" -o "$mihoctl_core_log""#));
        assert!(script.contains("mihoctl_core_log='/var/log/mihoctl/core.log'"));
        assert!(script.contains("pgrep -q -f \"$mihoctl_core_pattern\""));
        assert!(script.contains(r#"/usr/bin/pgrep -q -F "$pidfile" -L daemon"#));
        // The config, read via `-f`, is the only user path the root script references.
        assert_eq!(script.matches("/home/").count(), 1);
    }

    #[test]
    fn cron_block_quotes_and_replaces_only_its_own_block() {
        let old = "MAILTO=\"\"\n0 3 * * * /bin/backup\n# mihoctl_refresh begin\n@60 old\n# mihoctl_refresh end\n";
        let block = refresh_block(
            Path::new("/opt/mihoctl"),
            Path::new("/home/u/m it.toml"),
            Path::new("/home/u/core/refresh.log"),
            3600,
            "/usr/local/bin:/usr/bin:/bin",
        );
        let next = replace_block(old, &block);
        assert!(next.contains("0 3 * * * /bin/backup\n"));
        assert!(!next.contains("@60 old"));
        assert!(next.contains(
            "@3600 umask 077; MIHOCTL_CONFIG='/home/u/m it.toml' PATH='/usr/local/bin:/usr/bin:/bin' '/opt/mihoctl' refresh >> '/home/u/core/refresh.log' 2>&1"
        ));
        assert!(scheduled(&next));
        assert_eq!(replace_block(&next, &block), next);
        assert_eq!(replace_block(&next, ""), "MAILTO=\"\"\n0 3 * * * /bin/backup\n");
    }

    #[test]
    fn generated_shell_parses() {
        let dir = std::env::temp_dir().join(format!("mihoctl-rc-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let files = [
            ("core", core_script(&paths())),
            ("install", INSTALL_SH.to_string()),
            ("uninstall", UNINSTALL_SH.to_string()),
        ];
        for (name, contents) in files {
            let path = dir.join(name);
            std::fs::write(&path, contents).unwrap();
            let path = path.to_string_lossy();
            let ok = Command::new("/bin/sh").args(["-n", &path]).status().is_ok_and(|s| s.success());
            assert!(ok, "{name} does not parse");
        }
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn quotes_percent_for_cron() {
        assert_eq!(cron_quote("/a%b"), r"'/a\%b'");
        assert_eq!(sh_quote("a'b"), r"'a'\''b'");
    }
}
